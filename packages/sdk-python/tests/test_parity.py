"""Cross-language parity: the Python engine must reproduce every result of the TypeScript engine.

Fixtures: ``packages/engine/fixtures/parity.json`` (generated by ``generate-parity.mjs`` from the
TypeScript source). Override the location with ``NANOFLAGS_PARITY_FIXTURES``.
"""

from __future__ import annotations

import copy
import json
import os
from pathlib import Path
from typing import Any, Dict

import pytest

from nanoflags.engine import ENGINE_VERSION, bucket_of, client_bundle, evaluate, murmur3, supports_engine


def _fixture_path() -> Path:
    env = os.environ.get("NANOFLAGS_PARITY_FIXTURES")
    if env:
        return Path(env)
    return Path(__file__).resolve().parents[2] / "engine" / "fixtures" / "parity.json"


PATH = _fixture_path()
if not PATH.exists():  # pragma: no cover - only outside the monorepo layout
    pytest.skip(f"parity fixtures not found at {PATH}", allow_module_level=True)

DATA: Dict[str, Any] = json.loads(PATH.read_text(encoding="utf-8"))


def test_fixture_engine_version_matches() -> None:
    assert DATA["engineVersion"] == ENGINE_VERSION
    assert DATA["counts"]["cases"] == len(DATA["cases"])


def test_murmur3_vectors() -> None:
    bad = [c for c in DATA["murmur3"] if murmur3(c["input"], c["seed"]) != c["hash"]]
    assert not bad, bad[:5]
    assert len(DATA["murmur3"]) > 300


def test_bucket_vectors() -> None:
    bad = [c for c in DATA["buckets"] if bucket_of(c["seed"], c["identity"]) != c["bucket"]]
    assert not bad, bad[:5]


def test_supports_engine() -> None:
    for c in DATA["supportsEngine"]:
        assert supports_engine(c["bundle"]) is c["expected"], c


def test_client_bundle() -> None:
    for c in DATA["clientBundle"]:
        assert client_bundle(c["bundle"]) == c["expected"]


def _compare(case: Dict[str, Any]) -> list:
    bundle = None if case["bundle"] == -1 else copy.deepcopy(DATA["bundles"][case["bundle"]])
    ctx = copy.deepcopy(DATA["contexts"][case["context"]])
    e = evaluate(bundle, case["flag"], ctx, case["fallback"])
    x = case["expected"]
    problems = []

    def check(name: str, actual: Any, expected: Any) -> None:
        # JSON has one number type: 1 and 1.0 are the same value, but True is not 1.
        if json.dumps(actual, sort_keys=False) != json.dumps(expected, sort_keys=False) and not (
            type(actual) in (int, float) and type(expected) in (int, float) and float(actual) == float(expected)
        ):
            problems.append(f"{name}: python={actual!r} ts={expected!r}")

    check("reason", e.reason, x["reason"])
    check("value", e.value, x.get("value"))
    check("revision", e.revision, x["revision"])
    check("ruleIndex", e.rule_index, x.get("ruleIndex"))
    check("ruleId", e.rule_id, x.get("ruleId"))
    check("inRollout", e.in_rollout, x.get("inRollout"))
    check("bucket", e.bucket, x.get("bucket"))
    check("error", e.error is not None, x.get("error", False))
    if "trace" in x:
        mine = [t.to_dict() for t in e.trace]
        theirs = x["trace"]
        if x.get("error") and mine and theirs:
            # Error messages are engine-specific ("Cannot read properties of null …"); the steps before are not.
            mine[-1] = {**mine[-1], "detail": None}
            theirs = [*theirs[:-1], {**theirs[-1], "detail": None}]
        if mine != theirs:
            problems.append(f"trace: python={mine!r} ts={theirs!r}")
    return problems


def test_evaluation_cases() -> None:
    failures = []
    for case in DATA["cases"]:
        p = _compare(case)
        if p:
            failures.append((case["name"], p))
    assert len(DATA["cases"]) > 20000
    assert not failures, f"{len(failures)} of {len(DATA['cases'])} cases differ, e.g. {failures[:8]}"
